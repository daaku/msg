// icon renders a named inline SVG icon. It panics on an unknown name, which
// is a programming error.
func icon(name string) g.Node {
	paths, ok := icons[name]
	if !ok {
		panic("unknown icon: " + name)
	}
	return h.SVG(h.Class("icon icon-"+name), g.Attr("viewBox", "0 0 16 16"),
		g.Attr("aria-hidden", "true"), g.Attr("focusable", "false"), g.Raw(paths))
}
