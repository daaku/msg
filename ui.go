// shell renders the document around the given body content.
func (a *app) shell(w http.ResponseWriter, r *http.Request, title, bodyClass string, body ...g.Node) g.Node {
	w.Header().Set("Content-Type", "text/html; charset=utf-8")
	return h.Doctype(
		h.HTML(h.Lang("en"),
			h.Head(
				h.Meta(h.Charset("utf-8")),
				h.Meta(h.Name("viewport"),
					h.Content("width=device-width, initial-scale=1, viewport-fit=cover")),
				h.Meta(h.Name("color-scheme"), h.Content("light dark")),
				h.TitleEl(g.Text(title+" · "+a.cfg.AppName)),
				h.Link(h.Rel("stylesheet"), h.Href(assetPath("main.css"))),
				h.Script(h.Src(assetPath("main.js")), h.Defer()),
				g.If(a.cfg.Dev, h.Script(h.Src(pLivereloadJS), h.Defer())),
			),
			h.Body(g.If(bodyClass != "", h.Class(bodyClass)),
				h.Main(h.ID("app"),
					a.renderFlash(w, r),
					g.Group(body)))))
}

// page is the standard application page.
func (a *app) page(w http.ResponseWriter, r *http.Request, title string, body ...g.Node) g.Node {
	return a.shell(w, r, title, "", body...)
}

// pageSimple is a centred single column page with a heading and an optional
// back link, used for sign in, invites and errors.
func (a *app) pageSimple(w http.ResponseWriter, r *http.Request, title string, back g.Node, body ...g.Node) g.Node {
	return a.shell(w, r, title, "simple",
		h.Div(h.Class("simple-col stack"),
			pageHeader(title, back),
			g.Group(body)))
}

// pageHeader is a heading with an optional back link before it.
func pageHeader(title string, back g.Node) g.Node {
	return h.Header(h.Class("page-header"), back, h.H1(g.Text(title)))
}

// backLink is the visible back link every page other than home has.
func backLink(href, label string) g.Node {
	return h.A(h.Class("back"), h.Href(href), icon("back"), h.Span(g.Text(label)))
}

// fmtBytes formats a byte count with binary units, as in "1.5 MB".
func fmtBytes(n int64) string {
	const unit = 1024
	if n < unit {
		return strconv.FormatInt(n, 10) + " B"
	}
	units := []string{"KB", "MB", "GB", "TB", "PB", "EB"}
	v := float64(n) / unit
	i := 0
	for v >= unit && i < len(units)-1 {
		v /= unit
		i++
	}
	s := fmt.Sprintf("%.1f", v)
	if s == "1024.0" && i < len(units)-1 { // rounding up crossed a unit
		s, i = "1.0", i+1
	}
	return strings.TrimSuffix(s, ".0") + " " + units[i]
}

// fmtTime formats a timestamp in the given location (UTC when nil).
func fmtTime(t time.Time, loc *time.Location) string {
	if loc == nil {
		loc = time.UTC
	}
	return t.In(loc).Format("2 Jan 2006 15:04")
}

